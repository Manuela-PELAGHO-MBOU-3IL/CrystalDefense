    // Upper case and without accents: "Vague terminée" → "VAGUE TERMINEE".
    public static string Normalize(string text)
    {
        var builder = new StringBuilder(text.Length);
        foreach (char c in text.Normalize(NormalizationForm.FormD))
        {
            if (CharUnicodeInfo.GetUnicodeCategory(c) == UnicodeCategory.NonSpacingMark)
                continue;
            builder.Append(char.ToUpperInvariant(c));
        }
        return builder.ToString();
    }

    public static bool TryGetGlyph(char c, out string[] rows)
    {
        if (Glyphs.TryGetValue(c, out string[]? found))
        {
            rows = found;
            return true;
        }

        rows = Array.Empty<string>();
        return false;
    }

    // Width in screen pixels of a text drawn with the given size of one font pixel.
    public static float Measure(string text, float pixelSize) =>
        text.Length == 0 ? 0 : (text.Length * Advance - 1) * pixelSize;
